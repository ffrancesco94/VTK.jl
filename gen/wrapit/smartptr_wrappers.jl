# smartptr_wrappers.jl — generate Julia smart-pointer forwarding overloads
# for CxxWrap methods whose C++ signatures contain raw VTK pointers.
#
# The low-level bindings remain raw-pointer based. Each generated overload
# unwraps SmartPointer arguments with _cp(ExpectedType, value) and dispatches
# back to the low-level method. Non-VTK arguments stay untyped here: the
# low-level overload set continues to dispatch on their scalar/container types.

const VTK_RAW_ARG_RE = r"^(?:const\s+)?(vtk[A-Za-z0-9_]+)\s*\*$"
const JULIA_KEYWORDS = Set(["begin", "end", "if", "else", "elseif", "for",
    "while", "function", "return", "do", "let", "const", "global", "local",
    "struct", "mutable", "module", "baremodule", "using", "import", "export",
    "quote", "macro", "try", "catch", "finally", "break", "continue", "true",
    "false", "nothing"])

# Parse actual registrations rather than WrapIt's veto comments. This sees the
# exported Julia name (including renames), ignores static/module methods with
# no VTK-pointer argument, and covers WrapIt, the hand shim, and the auto-shim.
function smartptr_registrations(cxx)
    methods = NamedTuple[]
    for m in eachmatch(r"(?:t|module_|mod)\.method\(\"([^\"]+)\",\s*\[\]\((.*?)\)\s*(?:->|\{)"s, cxx)
        name, argstring = m.captures
        args = split(argstring, ',')
        types = String[]
        vtk_positions = Int[]
        for (i, arg) in enumerate(args)
            # Registration lambdas name their parameters. Remove the name,
            # then recognize only plain (possibly const) VTK pointers.
            tokens = split(strip(arg), ' ')
            length(tokens) > 1 && pop!(tokens)
            argtype = replace(join(tokens, ' '), r"\s+" => " ")
            push!(types, argtype)
            vm = match(VTK_RAW_ARG_RE, argtype)
            vm === nothing || (types[i] = vm.captures[1]; push!(vtk_positions, i))
        end
        # WrapIt emits reference and pointer overload pairs. Only mirror the
        # pointer registration: a reference receiver plus pointer argument
        # would create a partial wrapper and ambiguities with base-class APIs.
        1 in vtk_positions && push!(methods,
            (name = name, types = types, vtk_positions = vtk_positions))
    end
    return methods
end

function generate_smartptr_wrappers!(driver_dir, build_dir, output_path)
    sources = [joinpath(build_dir, "cxx", "JlClasses.cxx"),
               joinpath(driver_dir, "shim_vtkjl.cpp"),
               joinpath(build_dir, "cxx", "shim_auto.cpp")]
    registrations = reduce(vcat, smartptr_registrations.(read.(sources, String)))
    registered = Set(m.captures[1] for m in eachmatch(
        r"add_type<(vtk[A-Za-z0-9_]+)>", read(sources[1], String)))
    # VTK typedefs such as vtkMTimeType look like classes textually, but only
    # add_type-registered classes are valid SmartPointer parameters in Julia.
    filter!(m -> all(m.types[i] in registered for i in m.vtk_positions),
            registrations)

    # Scalar-only overload differences need just one forwarding method: after
    # unwrapping VTK pointers, the original raw-pointer overloads do the rest.
    unique_methods = Dict{Tuple,NamedTuple}()
    for method in registrations
        key = (method.name,
               Tuple(i in method.vtk_positions ? method.types[i] : nothing
                     for i in eachindex(method.types)))
        unique_methods[key] = method
    end

    out = String[
        "# AUTO-GENERATED by gen/wrapit/smartptr_wrappers.jl — do not edit.",
        "# Regenerated by gen/build_wrapper.jl after the C++ binding surface is final.",
        "# Raw-pointer overloads remain available; these only unwrap SmartPointers.",
        ""
    ]
    for method in sort(collect(values(unique_methods));
                       by = m -> (m.name, m.types, m.vtk_positions))
        args = String[]
        converted = String[]
        for i in eachindex(method.types)
            arg = "a$i"
            if i in method.vtk_positions
                push!(args,
                    "$arg::CxxWrap.CxxWrapCore.SmartPointer{<:$(method.types[i])}")
                push!(converted, "_cp($(method.types[i]), $arg)")
            else
                push!(args, arg)
                push!(converted, arg)
            end
        end
        name = method.name in JULIA_KEYWORDS ? "var\"$(method.name)\"" : method.name
        # The legacy fallback registers fewer classes. Guards are evaluated
        # after @wrapmodule, so its precompile sees only available types.
        guard = join(vcat("isdefined(@__MODULE__, Symbol(\"$(method.name)\"))",
                          ["isdefined(@__MODULE__, :$(method.types[i]))"
                           for i in method.vtk_positions]), " && ")
        push!(out, "if $guard")
        push!(out, "    $name($(join(args, ", "))) =")
        push!(out, "        $name($(join(converted, ", ")))")
        push!(out, "end")
        push!(out, "")
    end
    # Some generated VTK classes have an incomplete Julia parent chain (their
    # C++ parent is unmappable and their Julia supertype is Any). Add broad
    # fallbacks for generic base-class shim APIs so those objects still work.
    # Concrete-class registrations are excluded, avoiding cross-class clashes
    # such as the many SetFileName overloads. More specific typed overloads
    # above win whenever the Julia hierarchy is available.
    generic_bases = Set(["vtkObjectBase", "vtkAbstractArray", "vtkDataArray",
        "vtkFieldData", "vtkDataObject", "vtkAlgorithm", "vtkDataSet",
        "vtkPointSet"])
    hand_registrations = smartptr_registrations(read(sources[2], String))
    generic = Dict{Tuple,NamedTuple}()
    ambiguous = Set{Tuple}()
    for method in hand_registrations
        1 in method.vtk_positions || continue
        method.types[1] in generic_bases || continue
        all(method.types[i] in registered for i in method.vtk_positions) || continue
        key = (method.name, length(method.types), method.vtk_positions)
        if haskey(generic, key)
            delete!(generic, key)
            push!(ambiguous, key)
        elseif !(key in ambiguous)
            generic[key] = method
        end
    end
    push!(out, "# Hierarchy-independent fallbacks for generic base-class shim APIs.")
    push!(out, "")
    for method in sort(collect(values(generic)); by = m -> (m.name, m.types))
        args = String[]
        converted = String[]
        for i in eachindex(method.types)
            arg = "a$i"
            if i in method.vtk_positions
                push!(args, "$arg::CxxWrap.CxxWrapCore.SmartPointer")
                push!(converted, "_cp($(method.types[i]), $arg)")
            else
                push!(args, arg)
                push!(converted, arg)
            end
        end
        push!(out, "$(method.name)($(join(args, ", "))) =")
        push!(out, "    $(method.name)($(join(converted, ", ")))")
        push!(out, "")
    end
    write(output_path, join(out, "\n"))
    println("smart-pointer wrappers: ", length(unique_methods), " typed + ",
            length(generic), " generic Julia forwarding methods -> ", output_path)
    return nothing
end
